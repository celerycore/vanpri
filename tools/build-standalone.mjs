import { readFile, readdir, mkdir, writeFile, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { deflateRawSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { createZip } from '../src/zip.js';
import { gameFiles } from '../src/downloads.js';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const mime = { '.json': 'application/json', '.webp': 'image/webp', '.ogg': 'audio/ogg' };
const encoder = new TextEncoder();

async function atomicWrite(filename, data) {
  const temporary = filename + `.${process.pid}.tmp`;
  await writeFile(temporary, data);
  await rename(temporary, filename);
}

async function sourceFiles() {
  const files = [];
  async function walk(directory) {
    for (const entry of (await readdir(path.join(root, directory), { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
      if (entry.name.startsWith('.') || entry.name === '__pycache__' || entry.name.endsWith('.pyc')) continue;
      const relative = path.posix.join(directory, entry.name);
      if (entry.isDirectory()) await walk(relative);
      else if (entry.isFile()) files.push({ name: 'vanpri-browser/' + relative, data: await readFile(path.join(root, relative)) });
    }
  }
  for (const filename of ['.gitignore', '.nojekyll', 'DEPLOYMENT.md', 'package.json', 'server.mjs', 'README.md', 'ARCHIVE_STUDY.md', 'VERIFICATION.md']) {
    files.push({ name: 'vanpri-browser/' + filename, data: await readFile(path.join(root, filename)) });
  }
  files.push({ name: 'vanpri-browser/index.html', data: await readFile(path.join(root, 'src/page.html')) });
  for (const directory of ['src', 'tools', 'tests', 'assets']) await walk(directory);
  return files;
}

function compress(entries) {
  return createZip(entries.map(entry => {
    const data = typeof entry.data === 'string' ? encoder.encode(entry.data) : entry.data;
    return { ...entry, data, compressed: deflateRawSync(data, { level: 6 }) };
  }));
}

export async function buildDistribution() {
  // Loading already-embedded game metadata must not depend on fetch(data:...):
  // previews can deny connect-src even when scripts and embedded images work.
  const manifest = JSON.parse(await readFile(path.join(root, 'assets/manifest.json'), 'utf8'));
  await atomicWrite(path.join(root, 'src/game-manifest.js'), '// Generated by npm run build from assets/manifest.json.\nexport const GAME_MANIFEST = ' + JSON.stringify(manifest) + ';\n');
  const urls = {};
  for (const name of (await readdir(path.join(root, 'assets'))).sort()) {
    const type = mime[path.extname(name)];
    if (type) urls[name] = `data:${type};base64,${(await readFile(path.join(root, 'assets', name))).toString('base64')}`;
  }
  let code = '';
  for (const name of ['game-manifest.js', 'combat-data.js', 'combat-geometry.js', 'impact-effects.js', 'asset-url.js', 'zip.js', 'downloads.js', 'engine.js', 'renderer.js', 'audio.js', 'input.js', 'sprite-data.js', 'sprite-inspector.js', 'app.js']) {
    const source = await readFile(path.join(root, 'src', name), 'utf8');
    code += '\n' + source.replace(/^import .*?;\s*$/gm, '').replace(/^export (?=(?:class|const|let|function)\b)/gm, '');
  }
  const css = await readFile(path.join(root, 'src/styles.css'), 'utf8');
  let html = await readFile(path.join(root, 'src/page.html'), 'utf8');
  const boot = `globalThis.__VANGUARD_BUNDLE__=${JSON.stringify(urls)};\n` +
    // Capture the pristine page before the app populates the menu. Downloads can
    // save this exact playable document, including when the browser is offline.
    `globalThis.__VANGUARD_SOURCE__='<!doctype html>'+document.documentElement.outerHTML;\n` +
    `(async()=>{${code}\n})().catch(console.error);`;
  html = html.replace('<html lang="en">', '<html lang="en" data-standalone>')
    .replace('<link rel="stylesheet" href="./src/styles.css">', `<style>${css}</style>`)
    .replace('  <script type="module" src="./src/app.js"></script>\n', '')
    .replace('href="./" aria-label="Vanguard Princess home"', 'href="#" aria-label="Vanguard Princess home"')
    .replace('href="./dist/Vanguard-Princess.html?download=1"', 'href="./Vanguard-Princess.html?download=1"')
    .replace('href="./dist/downloads/Vanguard-Princess-Playable.zip"', 'href="./downloads/Vanguard-Princess-Playable.zip"')
    .replace('</body>', `<script>${boot}</script>\n</body>`);

  const dist = path.join(root, 'dist');
  await mkdir(path.join(dist, 'downloads'), { recursive: true });
  const releases = [
    { name: 'Vanguard-Princess.html', data: encoder.encode(html) },
    { name: 'downloads/Vanguard-Princess-Playable.zip', data: compress(gameFiles(html)) },
    { name: 'downloads/Vanguard-Princess-Source.zip', data: compress(await sourceFiles()) },
    { name: 'downloads/Vanguard-Princess-Website.zip', data: compress([
      { name: 'index.html', data: html },
      { name: 'HOSTING.txt', data: 'VANGUARD PRINCESS — WEBSITE BUILD\n\nUpload index.html to any static website host, at the root or inside a subfolder.\nIt includes all game code, images, music and browser download buttons.\nNo Node.js, credentials, server functions or asset CDN are required on the host.\nOpen the hosted page, choose your fighter and press ENTER THE ARENA.\nThe Download game and Download ZIP buttons also work offline.\n\nPublishing a Codex environment saves a development snapshot; it does not deploy this website.\nNo website was published by creating this package.\n' },
      gameFiles(html)[2],
    ]) },
  ];
  await atomicWrite(path.join(dist, 'index.html'), html);
  // Web previews commonly open only the project entry page. It must contain
  // the same complete game, rather than depend on external workspace files.
  await atomicWrite(path.join(root, 'index.html'), html);
  for (const release of releases) await atomicWrite(path.join(dist, release.name), release.data);
  const metadata = releases.map(file => ({ name: file.name, bytes: file.data.length, sha256: createHash('sha256').update(file.data).digest('hex') }));
  await atomicWrite(path.join(dist, 'release.json'), JSON.stringify({ files: metadata }, null, 2));
  return metadata;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const file of await buildDistribution()) console.log(`Built ${file.name} (${(file.bytes / 1024 / 1024).toFixed(1)} MiB)`);
  console.log('dist/index.html is ready for static hosting. Offline game and release ZIPs are also included.');
}
